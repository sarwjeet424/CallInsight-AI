"""
ReportGenerator — builds a rich Markdown report from the analysis results.
"""
import datetime


class ReportGenerator:

    RATING_EMOJI = {
        "Excellent": "🟢",
        "Good":      "🔵",
        "Average":   "🟡",
        "Poor":      "🔴",
    }

    DIMENSION_EMOJI = {
        "teaching_quality":    "🧑‍🏫",
        "student_engagement":  "🙋",
        "content_structure":   "📐",
        "communication":       "🗣️",
        "visual_presentation": "🖥️",
    }

    def build(self, result: dict, extraction: dict) -> str:
        rating  = result.get("rating", "Average")
        score   = result.get("score",  50)
        emoji   = self.RATING_EMOJI.get(rating, "⭕")
        now     = datetime.datetime.now().strftime("%Y-%m-%d %H:%M")
        duration_min = extraction.get("duration_seconds", 0) / 60
        n_frames = len(extraction.get("frame_paths", []))
        frame_interval = extraction.get("frame_interval", 30)

        bar = self._score_bar(score)

        lines = [
            f"# {emoji} ClassInsight AI Report",
            f"*Generated: {now}*",
            "",
            "---",
            "",
            f"## Overall Rating: **{rating}**",
            "",
            f"**Quality Score: {score}/100**",
            f"`{bar}` {score}%",
            "",
            "### Executive Summary",
            "",
            result.get("summary", ""),
            "",
            "---",
            "",
            "## 📊 Dimension Scores",
            "",
        ]

        dim_scores = result.get("dimension_scores", {})
        for dim, val in dim_scores.items():
            em = self.DIMENSION_EMOJI.get(dim, "📌")
            label = dim.replace("_", " ").title()
            bar_d = self._score_bar(val, width=20)
            lines.append(f"| {em} **{label}** | `{bar_d}` | **{val}/100** |")

        lines = lines + [
            "",
            "---",
            "",
            "## 🔍 Key Observations",
            "",
        ]

        for obs in result.get("observations", []):
            lines.append(f"- {obs}")

        lines += [
            "",
            "---",
            "",
            "## ✅ Strengths",
            "",
        ]
        for s in result.get("strengths", []):
            lines.append(f"- ✅ {s}")

        lines += [
            "",
            "## ⚠️ Areas for Improvement",
            "",
        ]
        for w in result.get("weaknesses", []):
            lines.append(f"- ⚠️ {w}")

        lines += [
            "",
            "---",
            "",
            "## 💡 Top Recommendation",
            "",
            f"> {result.get('recommendation', 'N/A')}",
            "",
            "---",
            "",
            "## 📂 Processing Details",
            "",
            f"| Parameter | Value |",
            f"|---|---|",
            f"| Recording Duration | {duration_min:.1f} minutes |",
            f"| Frames Analysed | {n_frames} (every {frame_interval}s) |",
            f"| Analysis Date | {now} |",
            f"| Models Used | Whisper · Llama 4 Maverick · Gemini Flash (OpenRouter free tier) |",
            "",
            "---",
            "*Report generated by ClassInsight AI — Humaniti AI Recruitment Challenge*",
        ]

        return "\n".join(lines)

    def _score_bar(self, score: int, width: int = 30) -> str:
        filled = round(score / 100 * width)
        return "█" * filled + "░" * (width - filled)
